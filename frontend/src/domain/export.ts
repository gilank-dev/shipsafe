import { agentLabel } from '../config/agents'
import type { AgentTarget, Finding, AuditReport } from './types'

export interface WhiteLabelConfig {
  companyName: string
  logoUrl?: string
}

/** Copy All Prompts: one header per finding, then its prompt (spec 6.3). */
export function buildPromptsMarkdown(findings: readonly Finding[], target: AgentTarget): string {
  const head = `# ShipSafe remediation prompts for ${agentLabel(target)}\n`
  const body = findings
    .map((f) => `## ${f.id} ${f.title} (${f.severity})\n\n${f.remediationPrompt}`)
    .join('\n\n---\n\n')
  return `${head}\n${body}\n`
}

export function promptFilename(target: AgentTarget): string {
  return `shipsafe-remediation-prompts-${target.toLowerCase()}.md`
}

/** Full comprehensive Markdown audit report for Pro / Enterprise export */
export function buildFullReportMarkdown(
  report: AuditReport,
  projectName: string,
  whiteLabel?: WhiteLabelConfig
): string {
  const branding = whiteLabel?.companyName
    ? `# Security Audit Report - ${whiteLabel.companyName}\n**Project:** ${projectName}\n`
    : `# ShipSafe Pre-Deployment Security Audit Report\n**Project:** ${projectName}\n`

  const date = report.createdAt ? new Date(report.createdAt).toLocaleString('id-ID') : new Date().toLocaleString('id-ID')

  const summarySection = `
**Audit Date:** ${date}  
**Overall Risk Status:** ${report.summary || 'Completed'}  

### Findings Breakdown
- **Critical:** ${report.countsBySeverity.Critical}
- **High:** ${report.countsBySeverity.High}
- **Medium:** ${report.countsBySeverity.Medium}
- **Low:** ${report.countsBySeverity.Low}
- **Info:** ${report.countsBySeverity.Info}

---
`

  const findingsSection = (report.findings || [])
    .map(
      (f, idx) => `
### ${idx + 1}. [${f.severity}] ${f.id} - ${f.title}
- **Threat Vector:** ${f.area}
- **Location:** \`${f.location?.file || 'N/A'}${f.location?.line ? `:${f.location.line}` : ''}\`
- **Confidence:** ${f.confidence || 'Confirmed'}

**What Was Found:**  
${f.what}

**Why It Matters (Risk):**  
${f.why}

**Recommended Fix:**  
${f.recommendedFix}

${f.verifyWith ? `**Verify Command:** \`${f.verifyWith}\`\n` : ''}
${f.remediationPrompt ? `**AI Remediation Prompt:**\n\`\`\`markdown\n${f.remediationPrompt}\n\`\`\`\n` : ''}
---`
    )
    .join('\n')

  return `${branding}\n${summarySection}\n## Security Findings Detail\n${findingsSection}\n\n*Generated by ${whiteLabel?.companyName || 'ShipSafe Security Platform'}*`
}

/** Full structured JSON audit export */
export function buildReportJson(report: AuditReport, projectName: string): string {
  const exportPayload = {
    generator: 'ShipSafe Pre-Deployment Security Auditor',
    version: '3.0.0',
    exportedAt: new Date().toISOString(),
    project: projectName,
    report: {
      id: report.id,
      summary: report.summary,
      createdAt: report.createdAt,
      countsBySeverity: report.countsBySeverity,
      scorecard: report.scorecard,
      secretsToRotate: report.secretsToRotate || [],
      notAssessed: report.notAssessed || [],
      findings: report.findings,
    },
  }
  return JSON.stringify(exportPayload, null, 2)
}

